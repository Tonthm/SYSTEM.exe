/// <summary>
/// ประเภทของ Bullet Pattern ที่ศัตรูใช้ยิง
/// ใช้ระบุ "สาเหตุการตาย" สำหรับ Death Log และ Bullet Pattern Memory
/// เพิ่มชนิดใหม่ได้เรื่อย ๆ เมื่อออกแบบแพทเทิร์นเพิ่ม
///
/// สำคัญ: เพิ่มชนิดใหม่ให้ต่อท้ายเสมอ อย่าแทรกกลาง
/// เพราะ Unity เซฟ enum เป็นตัวเลข index — แทรกกลางแล้วค่าที่ตั้งไว้ใน Inspector จะเลื่อนหมด
/// </summary>
public enum BulletPatternType
{
    Aimed,          // ยิงตรงเข้าหาผู้เล่น
    RadialBurst,    // ยิงกระจายรอบทิศทางพร้อมกัน (วงกลม)
    Spiral,         // ยิงหมุนเป็นเกลียว
    SpreadCone,     // ยิงกระจายเป็นมุมแคบไปทางผู้เล่น
    WallSweep,      // กระสุนเรียงเป็นแนวกวาดพื้นที่
    Collision       // ไม่ใช่กระสุน — ตายจากการชนตัวศัตรูโดยตรง (ใช้กับ ContactDamage)
}
